// Markdown writes a GitHub-flavored Markdown report, suitable for a pull
// request comment or $GITHUB_STEP_SUMMARY.
func Markdown(w io.Writer, r *analyze.Report, opts Options) error {
	opts.normalize()
	bw := bufio.NewWriter(w)
	m := &mdWriter{w: bw, top: opts.Top}
	m.render(r, opts)
	return bw.Flush()
}

type mdWriter struct {
	w   *bufio.Writer
	top int
}

func (m *mdWriter) p(format string, args ...any) { fmt.Fprintf(m.w, format+"\n", args...) }

// code renders s as inline code, safe for table cells.
func code(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	ticks := "`"
	for strings.Contains(s, ticks) {
		ticks += "`"
	}
	pad := ""
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		pad = " "
	}
	return ticks + pad + s + pad + ticks
}

func (m *mdWriter) render(r *analyze.Report, opts Options) {
	s := r.Summary
	icon := "✅"
	headline := "no behavioral drift"
	if s.Drift {
		icon = "🔴"
		headline = VerdictLine(s)
	}
	m.p("### %s logdrift: %s", icon, headline)
	m.p("")
	m.p("Compared **%s** (%s lines) against %s %s (%s lines, %s templates).",
		mdEscape(r.Target.Name), Thousands(r.Target.Lines), Plural(len(r.Baselines), "baseline run"),
		mdEscape("("+baselineNames(r)+")"), Thousands(baselineLines(r)), Thousands(r.Templates))
	m.p("")
	if d := s.FirstDivergence; d != nil {
		m.p("**First divergence:** line %d — %s", d.Line, d.Reason)
		m.p("")
	}
	if pr := r.Progress; pr != nil && pr.Expected > 0 && pr.FirstMissed != "" {
		m.p("**Progress:** reached %d/%d baseline milestones; never reached %s.", pr.Reached, pr.Expected, code(Truncate(pr.FirstMissed, 120)))
		m.p("")
	}

	if len(r.Context) > 0 {
		m.p("```text")
		for _, c := range r.Context {
			gutter := "  "
			if c.Focus {
				gutter = "▶ "
			}
			m.p("%s%6d %s %s", gutter, c.Line, MarkCode(c.Marks), strings.ReplaceAll(Truncate(c.Text, 200), "```", "'''"))
		}
		m.p("```")
		m.p("")
	}

	if len(r.Novel) > 0 {
		items := TopNovel(r.Novel, m.top)
		m.p("#### Novel templates (%d)", len(r.Novel))
		m.p("| line | count | template |")
		m.p("|---:|---:|---|")
		for _, n := range items {
			mark := ""
			if n.Error {
				mark = "❗ "
			}
			m.p("| %d | %d | %s%s |", n.FirstLine, n.Count, mark, code(Truncate(n.Template, 160)))
		}
		m.more(len(r.Novel), len(items))
	}
	if len(r.Vanished) > 0 {
		n := min(m.top, len(r.Vanished))
		m.p("#### Vanished templates (%d)", len(r.Vanished))
		m.p("| baseline count | template |")
		m.p("|---:|---|")
		for _, v := range r.Vanished[:n] {
			lo, hi := minMax(v.BaseCounts)
			m.p("| %s | %s |", Range(lo, hi), code(Truncate(v.Template, 160)))
		}
		m.more(len(r.Vanished), n)
	}
	if len(r.Shifted) > 0 {
		n := min(m.top, len(r.Shifted))
		m.p("#### Frequency shifts (%d)", len(r.Shifted))
		m.p("| target | baseline | template |")
		m.p("|---:|---:|---|")
		for _, sh := range r.Shifted[:n] {
			arrow := "▲"
			if sh.Direction == "down" {
				arrow = "▼"
			}
			m.p("| %s %d | %s | %s |", arrow, sh.Target, Range(sh.BaseMin, sh.BaseMax), code(Truncate(sh.Template, 160)))
		}
		m.more(len(r.Shifted), n)
	}
	if len(r.ParamDrift) > 0 {
		n := min(m.top, len(r.ParamDrift))
		m.p("#### Parameter drift (%d)", len(r.ParamDrift))
		m.p("| line | slot | change | template |")
		m.p("|---:|---|---|---|")
		for _, pd := range r.ParamDrift[:n] {
			m.p("| %d | %s | %s | %s |", pd.FirstLine, code(pd.Slot), mdEscape(SlotChange(pd)), code(Truncate(pd.Template, 120)))
		}
		m.more(len(r.ParamDrift), n)
	}
	if len(r.Stalls) > 0 {
		n := min(m.top, len(r.Stalls))
		m.p("#### Stalls (%d)", len(r.Stalls))
		m.p("| line | silence | baseline max | before |")
		m.p("|---:|---:|---:|---|")
		for _, st := range r.Stalls[:n] {
			m.p("| %d | %s | %s | %s |", st.Line, Duration(st.Gap), Duration(st.Reference), code(Truncate(st.Template, 140)))
		}
		m.more(len(r.Stalls), n)
	}
	m.p("<sub>generated by logdrift %s</sub>", mdEscape(opts.Version))
}

func (m *mdWriter) more(total, shown int) {
	if total > shown {
		m.p("")
		m.p("<sub>…and %d more</sub>", total-shown)
	}
	m.p("")
}

var mdReplacer = strings.NewReplacer(`\`, `\\`, "|", `\|`, "*", `\*`, "_", `\_`, "<", "&lt;", ">", "&gt;", "`", "\\`", "[", `\[`, "]", `\]`)

func mdEscape(s string) string { return mdReplacer.Replace(s) }
